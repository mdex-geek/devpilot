export function getLanguageConfig(language: string | null): LanguageConfig {
  if (!language) return LANGUAGE_FALLBACK;
  return LANGUAGE_MAP[language] ?? LANGUAGE_FALLBACK;
}

export function getLanguageLabel(language: string | null): string {
  return language ?? 'Unknown';
}

